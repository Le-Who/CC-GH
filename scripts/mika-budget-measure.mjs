import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';
const [out,kind,mode]=process.argv.slice(2);
assert.ok(out&&['baseline','candidate'].includes(kind)&&['off','on'].includes(mode));
await fs.mkdir(out,{recursive:true});
const {runBuildPerfGuard}=await import(pathToFileURL(path.resolve('scripts/perf-build-guard.mjs')).href);
const report=await runBuildPerfGuard({reportPath:path.join(out,'build-budget.json'),quiet:true});
const graph=JSON.parse(await fs.readFile('dist/game-loading-graph.json','utf8'));
const qaModules=graph.chunks.flatMap(c=>c.modules).filter(m=>m.startsWith('src/games/companion-yard-v2/mika-qa/'));
assert.equal(qaModules.length>0,mode==='on','Mika mode label must match emitted module ownership');
await fs.writeFile(path.join(out,'game-loading-graph.json'),JSON.stringify(graph,null,2));
const glb=await fs.readFile('dist/assets/yard-mika-p2-qa/p2.glb');
assert.equal(glb.length,3671320);assert.equal(createHash('sha256').update(glb).digest('hex'),'2249774f8ced124451d3c46a8a69bc06a9889c7d9cc31c836a6dd868fd96f084');
assert.equal(report.budgets.maxGameChunkRawBytes,75000);
assert.equal(report.appliedPublicAssetsCeiling,277287267);
assert.equal(report.yardAssetPartition.otherNonFamilyAssets.ceilingBytes,73470314);
const target=graph.chunks.filter(c=>c.modules.some(m=>m==='src/games/companion-yard-v2/pip-prototype/projection.mjs'));
assert.equal(target.length,1);
const c=target[0];assert.equal(c.dataOnly,false);assert.equal(c.isEntry,false);
assert.ok(!report.failures.some(f=>f.id.startsWith('games.loading-graph.')),'Incomplete loading graph cannot establish a budget pass');
const byFile=new Map(graph.chunks.map(c=>[c.file,c]));
const visit=(file,seen=new Set())=>{if(seen.has(file))return seen;seen.add(file);for(const dep of byFile.get(file)?.imports||[])visit(dep,seen);return seen;};
if(kind==='candidate'){
 const leaf=await import(pathToFileURL(path.resolve('src/games/companion-yard-v2/pip-prototype/garden-raster.mjs')).href);
 const resources=await import(pathToFileURL(path.resolve('src/games/companion-yard-v2/pip-prototype/resources.mjs')).href);
 assert.equal(resources.GARDEN_RASTER,leaf.GARDEN_RASTER);assert.equal(resources.LIMITS.backing,leaf.GARDEN_RASTER);
 assert.match(c.file,/yard-pip-projection-/);
 assert.ok(c.gameModules.includes('src/games/companion-yard-v2/pip-prototype/projection.mjs'));
 assert.ok(report.metrics.gameChunks.files.some(f=>f.path===c.file),'Projection is missing from executable game budget inventory');
 assert.ok((await fs.stat(path.join('dist',c.file))).size<=75000,'Projection executable chunk exceeds unchanged limit');
 for(const d of c.imports)assert.ok(!visit(d).has(c.file),'Projection chunk initialization cycle');
 for(const entry of graph.chunks.filter(c=>c.isEntry))assert.ok(!visit(entry.file).has(c.file),'Projection promoted to startup');
 assert.ok(!report.failures.some(f=>f.id==='games.max-chunk.raw'),'Game chunk budget still fails');
 assert.ok(report.failures.every(f=>['public-assets.total.raw','public-assets.other-non-family.raw'].includes(f.id)),'Unexpected non-asset failure cannot be treated as split acceptance');
 if(process.env.MIKA_REQUIRE_SHIPPING_BUDGET==='true')assert.equal(report.passed,true,'Lossless candidate must pass every unchanged shipping budget');
}
await fs.writeFile(path.join(out,'measurement.json'),JSON.stringify({kind,mode,shippingPassed:report.passed,failures:report.failures,projectionChunk:c.file,projectionBytes:(await fs.stat(path.join('dist',c.file))).size,gameMaxBytes:report.metrics.gameChunks.maxRawBytes,mikaGlbBytes:glb.length,publicAssetsBytes:report.metrics.publicAssets.rawBytes,otherAssetsBytes:report.yardAssetPartition.otherNonFamilyAssets.rawBytes},null,2));
console.log(JSON.stringify({kind,mode,shippingPassed:report.passed,failures:report.failures}));
